/* sync-copy-payload.mjs — rebuild the Echo copy payload from the real source.
   Run:  node sync-copy-payload.mjs        (no dependencies)

   The Echo node's reader panel carries a Copy button whose payload is a
   self-contained listing: the projection, the shared plate vocabulary, the
   shape itself, and the contract. It exists to be handed to somebody — or
   something — that is learning to draw in this style.

   It is GENERATED, never hand-written, because a hand-copied listing drifts
   from the code it claims to be the moment either is touched, and a teaching
   example that is subtly not the real thing is worse than none. Everything
   below is lifted verbatim out of pipeline-iso.js and pipeline-shapes.js by
   name; the only authored text is the framing.

   It writes into index.html between the two BEGIN/END marker comments, and
   syntax-checks the result before it does.
*/
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const R = f => readFileSync(join(here, f), 'utf8');

const iso = R('pipeline-iso.js'), shapes = R('pipeline-shapes.js');

/* Pull a top-level `function name(...) { ... }` by brace balance. Regex alone
   cannot find the end of a function; this counts braces outside strings,
   template literals, regexes and comments, which is enough for this file. */
function fn(src, name) {
  const start = src.indexOf(`function ${name}(`);
  if (start < 0) throw new Error(`function ${name} not found`);
  let i = src.indexOf('{', start), depth = 0;
  for (; i < src.length; i++) {
    const c = src[i], p = src[i - 1];
    if (c === '/' && src[i + 1] === '*') { i = src.indexOf('*/', i) + 1; continue; }
    if (c === '/' && src[i + 1] === '/') { i = src.indexOf('\n', i); continue; }
    if (c === '"' || c === "'" || c === '`') {
      const q = c; i++;
      while (i < src.length && !(src[i] === q && src[i - 1] !== '\\')) i++;
      continue;
    }
    if (c === '{') depth++;
    else if (c === '}') { depth--; if (!depth) return src.slice(start, i + 1); }
  }
  throw new Error(`unbalanced braces in ${name}`);
}

/* Pull a `const NAME = ...;` or `const NAME = {...};` statement. */
function decl(src, name) {
  const re = new RegExp(`^const ${name}\\s*=`, 'm');
  const m = re.exec(src);
  if (!m) throw new Error(`const ${name} not found`);
  let i = m.index, depth = 0, seen = false;
  for (; i < src.length; i++) {
    const c = src[i];
    if (c === '{' || c === '[' || c === '(') { depth++; seen = true; }
    else if (c === '}' || c === ']' || c === ')') depth--;
    else if (c === ';' && depth === 0) return src.slice(m.index, i + 1);
    else if (c === '\n' && depth === 0 && seen) return src.slice(m.index, i);
  }
  throw new Error(`no terminator for ${name}`);
}

/* the leading block comment immediately above a function, if there is one */
function commentAbove(src, name) {
  const at = src.indexOf(`function ${name}(`);
  const before = src.slice(0, at);
  const open = before.lastIndexOf('/* ---');
  if (open < 0) return '';
  const close = before.indexOf('*/', open);
  if (close < 0 || before.slice(close).trim().length > 2) return '';
  return before.slice(open, close + 2) + '\n';
}

