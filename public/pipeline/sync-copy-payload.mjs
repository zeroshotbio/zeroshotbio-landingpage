/* it must be real JavaScript, or it is not the real code */
const tmp = join(here, '.copy-payload.check.js');
writeFileSync(tmp, out);
try { execFileSync(process.execPath, ['--check', tmp]); }
finally { try { execFileSync('rm', ['-f', tmp]); } catch {} }

if (out.includes('</script')) throw new Error('payload would close its own script block');

const BEGIN = '<!-- BEGIN copy-ECHO (generated by sync-copy-payload.mjs) -->';
const END = '<!-- END copy-ECHO -->';
const html = R('index.html');
const a = html.indexOf(BEGIN), b = html.indexOf(END);
if (a < 0 || b < 0) throw new Error('markers not found in index.html');

const block = `${BEGIN}\n<script type="text/plain" id="copy-ECHO">\n${out}</script>\n${END}`;
writeFileSync(join(here, 'index.html'), html.slice(0, a) + block + html.slice(b + END.length));

console.log(`copy-ECHO payload: ${out.length.toLocaleString()} chars, ${out.split('\n').length} lines — syntax ok, written into index.html`);
